show("sched priorities", os.sched_get_priority_max(os.SCHED_FIFO) == 99 and os.sched_get_priority_min(os.SCHED_FIFO) == 1 and os.sched_get_priority_max(os.SCHED_OTHER) == 0)
show("sched_rr_get_interval", os.sched_rr_get_interval(0) > 0)
