# Behaviors fixed after Python's own OS tests failed; each line ends in True
import os, select, pty, signal, sys, time, socket, errno
def show(name, ok): print(f"{name:42s} {bool(ok)}", flush=True)
os.makedirs("/tmp/osm", exist_ok=True)
if not os.path.exists("/tmp/osm/p"): os.mkfifo("/tmp/osm/p")
try: os.scandir("/tmp/osm/p"); show("opendir on a FIFO fails", False)
except NotADirectoryError: show("opendir on a FIFO fails", True)
r, w = os.pipe(); os.close(r); os.close(w)
p = select.poll(); p.register(r)
show("poll reports a closed fd", p.poll() == [(r, select.POLLNVAL)])
pid, master = pty.fork()
if pid == 0:
    os.write(1, b"hello from child\n"); os._exit(3)
data = b""; got_eio = False
while True:
    try: d = os.read(master, 80)
    except OSError as e: got_eio = e.errno == errno.EIO; break
    if not d: break
    data += d
show("pty master: data, then EIO", data == b"hello from child\r\n" and got_eio and os.waitpid(pid, 0)[1] >> 8 == 3)
signal.pthread_sigmask(signal.SIG_BLOCK, [signal.SIGALRM, signal.SIGUSR1])
signal.alarm(1); t = time.monotonic()
show("sigwait for a blocked alarm", signal.sigwait([signal.SIGALRM]) == signal.SIGALRM and 0.9 < time.monotonic() - t < 3)
os.kill(os.getpid(), signal.SIGUSR1)
show("sigwait, signal already pending", signal.sigwait([signal.SIGUSR1]) == signal.SIGUSR1)
os.kill(os.getpid(), signal.SIGUSR1)
show("same signal can arrive again", signal.sigtimedwait([signal.SIGUSR1], 1).si_signo == signal.SIGUSR1)
show("sigtimedwait times out", signal.sigtimedwait([signal.SIGUSR1], 0.2) is None)
a, b = socket.socketpair()
ep = select.epoll()
for s in (a, b): ep.register(s.fileno(), select.EPOLLIN | select.EPOLLOUT | select.EPOLLET)
show("epoll ET: writable once", sorted(ep.poll(1, 4)) == sorted([(a.fileno(), select.EPOLLOUT), (b.fileno(), select.EPOLLOUT)]))
show("epoll ET: not reported again", ep.poll(0.1, 4) == [])
a.send(b"x")
ev = dict(ep.poll(1, 4))
show("epoll ET: readable after send", ev.get(b.fileno(), 0) & select.EPOLLIN)
show("epoll ET: quiet again", ep.poll(0.1, 4) == [])
import resource, fcntl, mmap
